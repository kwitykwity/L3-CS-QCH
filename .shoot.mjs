import { chromium } from 'playwright';
const [base, tag, w = '1280', size = 'M', scheme = 'light'] = process.argv.slice(2);
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: Number(w), height: 900 }, colorScheme: scheme });
const p = await ctx.newPage();
await p.goto(base + '/demo/');
await p.getByRole('button', { name: /Referring Worker/ }).click();
await p.waitForURL(/referral/);
if (size !== 'M') await p.getByRole('button', { name: size, exact: true }).click();
await p.locator('#path-guided').click();
for (const i of [0, 1, 2, 3, 4]) await p.locator('#needs-options input').nth(i).check();
await p.locator('#find-programs').click();
await p.locator('#match-results').waitFor();
await p.waitForTimeout(400);
const y = await p.evaluate(() => document.getElementById('match-results').getBoundingClientRect().top + scrollY);
const h = await p.evaluate(() => document.getElementById('match-results').getBoundingClientRect().height);
await p.screenshot({ path: `/tmp/shots250/${tag}-${scheme}-${w}-${size}.png`, fullPage: true });
console.log(tag, Math.round(y), Math.round(h), await p.evaluate(() => document.documentElement.scrollWidth - innerWidth), await p.locator('.match').count());
await b.close();
